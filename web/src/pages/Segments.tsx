import { AlertTriangle, Info, Users } from "lucide-react";
import { Bar, BarChart, CartesianGrid, Cell, ReferenceLine, Tooltip, XAxis, YAxis } from "recharts";
import { useNavigate } from "react-router-dom";
import { Banner, Btn, Card, Chart, Empty, Sk, Tag } from "../components/ui";
import { useAsync } from "../hooks/useAsync";
import { getAttributeBreakdowns, getByContract, getOverview, getSegments } from "../lib/db";
import { pct } from "../lib/format";
import type { BreakdownRow } from "../lib/types";

const SEGMENTS: Record<string, { label: string; rule: string; actions: string[]; color: string }> = {
  new_month_to_month: { label: "New month-to-month customers", rule: "Month-to-month contract and tenure under 12 months", color: "#F43F5E",
    actions: ["Strengthen onboarding in the first months", "Offer an incentive to move to a longer contract", "Check in early to catch problems before they cancel"] },
  high_bill_no_tech_support: { label: "High bill, no tech support", rule: "Monthly charges above $85 and TechSupport = No", color: "#F59E0B",
    actions: ["Offer a tech-support add-on or a bill review", "Explain value for money on higher-priced plans", "Proactively check whether the plan still fits their usage"] },
  loyal_long_term: { label: "Loyal long-term customers", rule: "Tenure of 36+ months on a one- or two-year contract", color: "#10B981",
    actions: ["Recognise loyalty (rewards, early renewal offers)", "Ask for feedback and referrals", "Keep service quality consistent; avoid unnecessary price changes"] },
};
const tick = { fill: "#94A3B8", fontSize: 12 };
const tip = { background: "#0C1838", border: "1px solid rgba(148,163,184,.25)", borderRadius: 8, color: "#E2E8F0" };

function BreakdownCard({ title, rows }: { title: string; rows: BreakdownRow[] }) {
  return (
    <Card title={title}>
      {rows.length === 0 ? <p className="text-sm text-slate-500">No data yet.</p> : (
        <ul className="space-y-3">
          {rows.map((r) => { const v = r.avg_probability === null ? 0 : Number(r.avg_probability); return (
            <li key={r.label} className="text-sm">
              <div className="flex justify-between gap-2"><span className="text-slate-200">{r.label}</span><span className="text-slate-400">n={r.predictions} · {r.high} high · {r.avg_probability === null ? "n/a" : pct(v)}</span></div>
              <div className="mt-1 h-2 rounded-full bg-white/10"><div className="h-2 rounded-full bg-nfs-gradient" style={{ width: Math.min(100, v * 100) + "%" }} /></div>
            </li>); })}
        </ul>)}
    </Card>
  );
}

export default function Segments() {
  const navigate = useNavigate();
  const seg = useAsync(getSegments, []);
  const ov = useAsync(getOverview, []);
  const attrs = useAsync(getAttributeBreakdowns, []);
  const contracts = useAsync(getByContract, []);

  if (seg.loading || ov.loading) return <div className="space-y-4"><Sk h="h-32" /><Sk h="h-72" /></div>;
  if (seg.error || ov.error || !seg.data || !ov.data) return <Card><Empty icon={AlertTriangle} title="Could not load segments" text={seg.error || ov.error} action={<Btn onClick={() => { seg.reload(); ov.reload(); }}>Try again</Btn>} /></Card>;
  if (!ov.data.total_predictions) return <Card><Empty icon={Users} title="No segment data yet" text="Segments are computed from the predictions saved to your account. Run predictions first." action={<Btn onClick={() => navigate("/batch")}>Upload a CSV</Btn>} /></Card>;

  const overall = ov.data.avg_probability === null ? null : Number(ov.data.avg_probability);
  const chart = seg.data.filter((s) => s.size > 0 && s.avg_probability !== null).map((s) => ({ name: SEGMENTS[s.key]?.label ?? s.key, avg: Math.round(Number(s.avg_probability) * 1000) / 10, key: s.key }));

  return (
    <div className="space-y-5">
      <Banner>Segments are rule-based groups computed from your saved predictions. A customer can belong to more than one segment, so sizes do not add up. “Average risk” is the model’s predicted churn probability, not observed churn. The suggested actions are general guidance, not generated by an AI model.</Banner>
      <div className="grid gap-5 lg:grid-cols-3">
        {seg.data.map((s) => {
          const meta = SEGMENTS[s.key]; if (!meta) return null;
          return (
            <Card key={s.key} title={meta.label} sub={meta.rule}>
              {s.size === 0 ? <p className="text-sm text-slate-500">No customers in your saved predictions match this segment yet.</p> : (
                <div className="space-y-3 text-sm">
                  <div className="flex items-end justify-between"><div><p className="text-xs text-slate-400">Segment size</p><p className="text-3xl font-bold text-white">{s.size.toLocaleString()}</p></div>
                    <div className="text-right"><p className="text-xs text-slate-400">Avg predicted probability</p><p className="text-xl font-semibold" style={{ color: meta.color }}>{pct(Number(s.avg_probability))}</p></div></div>
                  <div className="flex h-2.5 overflow-hidden rounded-full bg-white/10" title="High / Medium / Low">
                    <div className="bg-rose-500" style={{ width: (s.high / s.size) * 100 + "%" }} /><div className="bg-amber-500" style={{ width: (s.medium / s.size) * 100 + "%" }} /><div className="bg-emerald-500" style={{ width: (s.low / s.size) * 100 + "%" }} />
                  </div>
                  <p className="text-xs text-slate-400">{s.high} high · {s.medium} medium · {s.low} low · avg tenure {s.avg_tenure ?? "n/a"} mo · avg bill ${s.avg_monthly_charges ?? "n/a"}</p>
                  <div><p className="mb-1 text-xs font-semibold uppercase text-slate-500">General retention ideas</p>
                    <ul className="list-disc space-y-1 pl-5 text-slate-300">{meta.actions.map((a) => <li key={a}>{a}</li>)}</ul></div>
                </div>)}
            </Card>);
        })}
      </div>
      <div className="grid gap-5 lg:grid-cols-3">
        <Card className="lg:col-span-2" title="Segment comparison" sub={overall === null ? "Average predicted probability by segment" : "Average predicted probability by segment (dashed line = all predictions, " + pct(overall) + ")"}>
          {chart.length === 0 ? <Empty icon={Users} title="Nothing to compare" text="No segment contains customers yet." /> : (
            <Chart><BarChart data={chart}>
              <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="rgba(148,163,184,.15)" />
              <XAxis dataKey="name" tick={tick} stroke="rgba(148,163,184,.3)" /><YAxis domain={[0, 100]} tick={tick} stroke="rgba(148,163,184,.3)" unit="%" />
              <Tooltip contentStyle={tip} cursor={{ fill: "rgba(255,255,255,.04)" }} />
              {overall !== null && <ReferenceLine y={overall * 100} stroke="#22D3EE" strokeDasharray="5 5" />}
              <Bar dataKey="avg" name="Avg probability %" radius={[4, 4, 0, 0]}>{chart.map((c) => <Cell key={c.key} fill={SEGMENTS[c.key]?.color ?? "#3B82F6"} />)}</Bar></BarChart></Chart>)}
        </Card>
        <Card title="Frequent support contacts" right={<Tag>unavailable</Tag>}>
          <div className="flex gap-3 text-sm text-slate-300"><Info className="mt-0.5 shrink-0 text-slate-400" size={18} />
            <p>This segment cannot be computed. The dataset behind the model has no support-ticket or call-count field, and NFS does not invent missing data.</p></div>
        </Card>
      </div>
      {(() => {
        const notes: string[] = [];
        const top = (rows: { label: string; predictions: number; avg_probability: number | null }[], what: string) => {
          const r = rows.filter((x) => x.avg_probability !== null && x.predictions > 0).sort((x, y) => Number(y.avg_probability) - Number(x.avg_probability));
          if (r.length >= 2) notes.push(`Highest average predicted risk by ${what}: ${r[0].label} (${pct(Number(r[0].avg_probability))}, n=${r[0].predictions}); lowest: ${r[r.length - 1].label} (${pct(Number(r[r.length - 1].avg_probability))}, n=${r[r.length - 1].predictions}).`);
        };
        top((contracts.data ?? []).map((c) => ({ label: c.contract, predictions: c.predictions, avg_probability: c.avg_probability })), "contract");
        if (attrs.data) { top(attrs.data.tenure_band, "tenure"); top(attrs.data.monthly_charge_band, "monthly charge"); top(attrs.data.tech_support, "tech-support status"); }
        const sized = seg.data.filter((s) => s.size > 0 && s.avg_probability !== null).sort((a, b) => Number(b.avg_probability) - Number(a.avg_probability));
        if (sized.length >= 2) notes.push(`Among the rule segments, “${SEGMENTS[sized[0].key]?.label}” has the highest average predicted risk (${pct(Number(sized[0].avg_probability))}, n=${sized[0].size}).`);
        return notes.length === 0 ? null : (
          <Card title="Key observations" sub="Computed from your saved predictions (no AI involved)">
            <ul className="list-disc space-y-1.5 pl-5 text-sm text-slate-300">{notes.map((n) => <li key={n}>{n}</li>)}</ul>
            <p className="mt-3 text-xs text-slate-500">These describe patterns in the model’s predictions, not proven causes or observed churn. Groups with few customers (small n) are unreliable. For a written analysis, use the AI Assistant or the Customer segment report.</p>
          </Card>);
      })()}
      <div>
        <h2 className="mb-1 text-lg font-semibold text-white">Explore by attribute</h2>
        <p className="mb-3 text-sm text-slate-400">Average predicted churn probability for groups formed from the customer fields NFS stores. Bars are scaled 0–100%; “n” is the number of saved predictions in the group.</p>
        {attrs.loading || contracts.loading ? <Sk h="h-48" /> : attrs.error || !attrs.data ? <Card><Empty icon={AlertTriangle} title="Could not load attribute breakdowns" text={attrs.error || "No data."} action={<Btn onClick={attrs.reload}>Try again</Btn>} /></Card> : (
          <div className="grid gap-5 lg:grid-cols-2">
            <BreakdownCard title="By contract type" rows={(contracts.data ?? []).map((c) => ({ label: c.contract, predictions: c.predictions, high: c.high, avg_probability: c.avg_probability }))} />
            <BreakdownCard title="By tenure" rows={attrs.data.tenure_band} />
            <BreakdownCard title="By monthly charge" rows={attrs.data.monthly_charge_band} />
            <BreakdownCard title="By tech-support status" rows={attrs.data.tech_support} />
          </div>)}
      </div>
    </div>
  );
}
